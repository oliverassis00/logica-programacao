# Área do retângulo
# Crie variáveis para largura e altura e calcule:
# Área
# Perímetro

altura = int(input('Digite a altura: '))
largura = int(input('Digite a largura: '))

calc_area = altura * largura
calc_perimetro = 2 * (altura + largura)

print(f''' 
A área do Retangulo é {calc_area}m²
O perímetro do Retangulo é {calc_perimetro}m
''')
