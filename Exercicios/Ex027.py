# 7. Detector de Fraude em Compras Online 🚨

# Receba:

# Valor da compra
# País da compra
# Quantidade de compras no dia

# Regras:

# Fraude suspeita se:

# valor > 5000

# ou

# compras_dia > 10

# ou

# pais != "Brasil"

# Classifique:

# Baixo Risco
# Médio Risco
# Alto Risco

# Dependendo da quantidade de critérios atendidos.

